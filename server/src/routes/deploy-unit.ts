import type { WriterBinding } from "@gbrain-cockpit/shared";

// 0.5.0 batch 3: the deploy-checkup card's generated unit text. Pure text
// generation — NOTHING here is executed by cockpit (copy-command channel in
// its purest form: reference material for the owner's terminal). The
// knowledge pinned below is the 2026-11-10 bip dream post-mortem
// (ENVIRONMENT §8.1-8.2), verified against gbrain 0.60.611 source.

/**
 * The pitfall notes the card renders (stable identifiers — the web maps
 * each to a locale key; the list is also the test oracle for completeness).
 */
export const DEPLOY_NOTES = [
  "repo-path-two-locks",
  "systemd-quoting",
  "propose-window",
  "grade-window-global",
  "cron-not-systemd",
] as const;

export interface DeployUnitInput {
  /** the profile's owner command name (wrapper) — "gbrain" when unset */
  cliBin: string;
  /** direct-call pair (multi-source brains): the REAL binary + brain home */
  gbrainBin?: string;
  gbrainHome?: string;
  /** writer bindings (source_id/local_path; default detection by path) */
  bindings: WriterBinding[];
}

/**
 * Build the per-source two-segment unit text: one freshness pass per source
 * (default rides full phases harmlessly — probed 2026-11-10), then the
 * calibration pass (propose_takes + grade_takes) per NON-default source —
 * the owner deletes sources that should not participate (bulk-document
 * sources nobody can adjudicate, e.g. bip's docs source).
 *
 * The text is reference material with a disclaimer; comments stay terse
 * terminal English, the card localizes the WHY around it.
 */
export function buildDeployUnitText(input: DeployUnitInput): string {
  const sources = input.bindings
    .map((b) => (typeof b.source_id === "string" ? b.source_id : ""))
    .filter(Boolean);
  const nonDefault = sources.filter((s) => s !== "default");
  const bin =
    input.gbrainBin && input.gbrainHome ? input.gbrainBin : input.cliBin;
  const homeLine = input.gbrainHome
    ? `Environment=GBRAIN_HOME=${input.gbrainHome}\n`
    : `# set GBRAIN_HOME when this unit targets a non-default brain\n`;
  const freshness = sources.map((s) => `"${bin}" dream --source "${s}" --json`).join("; ");
  const calibration = nonDefault
    .map(
      (s) =>
        `"${bin}" dream --source "${s}" --phase propose_takes --phase grade_takes --json`,
    )
    .join("; ");
  return [
    "# Reference unit text generated by cockpit — read it before installing;",
    "# cockpit never installs, edits or runs units (owner terminal only).",
    "# Delete any source that should not participate in the nightly cycle",
    "# (e.g. bulk-document sources nobody adjudicates).",
    "[Unit]",
    "Description=gbrain per-source nightly cycle (freshness + calibration)",
    "",
    "[Service]",
    "Type=oneshot",
    homeLine.trimEnd(),
    "# NOTE: the bash -c payload MUST stay single-quoted as a whole —",
    "# systemd expands bare $(...) in ExecStart and fails the unit.",
    'ExecStart=/bin/bash -c \'set -u; ' + freshness +
      "; " +
      calibration +
      "'",
    "",
    "# companion knowledge (see the card for details):",
    "# - sync.repo_path must point at the DEFAULT source's canonical checkout",
    "#   (lint/accept paths need it; any path matching a source local_path",
    "#   locks unscoped dream to that source — multi-source brains cannot",
    "#   use the unscoped form at all)",
    "# - propose window = latest 100 pages per source; the 2000-page",
    "#   source-cycle window is a different mechanism",
    "# - grade_takes grades the WHOLE brain's judged takes (no source filter)",
    "# - doctor's cron_gbrain_home watches crontab only; a missing/wrong",
    "#   systemd unit only shows up as cycle_freshness going stale",
  ].join("\n");
}
